#!/usr/bin/env bash
# Write hive-site.xml (embedded Derby metastore at a FIXED absolute path, MapReduce engine, HiveServer2 on 10000)
# and initialise the metastore schema once. A fixed path matters: Derby's default is relative to the current
# directory, which silently creates a new empty metastore (and loses your tables) whenever you start Hive elsewhere.
#
#   bash setup/configure_hive.sh [--force]
set -euo pipefail

PROJECT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FORCE=false
[[ "${1:-}" == "--force" ]] && FORCE=true

[[ -f "$PROJECT/config/fraudlens.env" ]] && source "$PROJECT/config/fraudlens.env"
HIVE_HOME="${HIVE_HOME:-$HOME/hive}"
if [[ ! -x "$HIVE_HOME/bin/schematool" ]]; then
    echo "ERROR: Hive not found at $HIVE_HOME. Install it (setup/install_toolchain.sh) and run setup/configure_environment.sh."
    exit 1
fi

DATA="${FRAUDLENS_DATA_DIR:-$HOME/hadoop_data}"
MARKER="generated by FraudLens setup/configure_hive.sh"
SITE="$HIVE_HOME/conf/hive-site.xml"
mkdir -p "$DATA"

if [[ -f "$SITE" ]] && ! grep -q "$MARKER" "$SITE"; then
    if [[ "$FORCE" == true ]]; then
        cp "$SITE" "$SITE.fraudlens-backup-$(date +%Y%m%d_%H%M%S)"
        echo "backed up existing hive-site.xml"
    else
        echo "KEPT existing hive-site.xml (hand-written). Rerun with --force to replace it."
        KEEP=true
    fi
fi

if [[ "${KEEP:-false}" != true ]]; then
    cat > "$SITE" <<XML
<?xml version="1.0"?>
<!-- $MARKER -->
<configuration>
  <property><name>javax.jdo.option.ConnectionURL</name><value>jdbc:derby:;databaseName=$DATA/hive_metastore_db;create=true</value></property>
  <property><name>javax.jdo.option.ConnectionDriverName</name><value>org.apache.derby.jdbc.EmbeddedDriver</value></property>
  <property><name>hive.metastore.warehouse.dir</name><value>/user/hive/warehouse</value></property>
  <property><name>hive.metastore.uris</name><value>thrift://localhost:9083</value></property>
  <property><name>hive.server2.thrift.port</name><value>10000</value></property>
  <property><name>hive.server2.thrift.bind.host</name><value>localhost</value></property>
  <property><name>hive.server2.enable.doAs</name><value>false</value></property>
  <property><name>hive.server2.authentication</name><value>NONE</value></property>
  <property><name>hive.execution.engine</name><value>mr</value></property>
  <property><name>hive.exec.scratchdir</name><value>/tmp/hive</value></property>
  <property><name>hive.metastore.event.db.notification.api.auth</name><value>false</value></property>
</configuration>
XML
    echo "wrote $SITE"
fi

if [[ -d "$DATA/hive_metastore_db" ]]; then
    echo "Hive metastore already initialised ($DATA/hive_metastore_db)."
else
    echo "Initialising the Hive metastore schema (Derby) ..."
    # Run from the data directory so derby.log does not land in the repository.
    (cd "$DATA" && JAVA_HOME="$JAVA_HOME" "$HIVE_HOME/bin/schematool" -dbType derby -initSchema)
fi
echo "Hive configuration ready."
